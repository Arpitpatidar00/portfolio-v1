/* ─── SEO Helpers ────────────────────────────────────────────
 * Single source of truth for URLs, page metadata and JSON-LD.
 * Every page builds its <head> through `buildPageMetadata` so
 * titles, descriptions, canonicals and social cards never drift.
 * ──────────────────────────────────────────────────────────── */

import type { Metadata } from "next";
import { siteConfig, socialLinks } from "@/constants/config";
import { PORTRAIT_URL } from "@/constants/media";

/**
 * Absolute origin of the deployed site (no trailing slash).
 *
 * Order of precedence:
 * 1. NEXT_PUBLIC_SITE_URL       – set this to your real domain in production
 * 2. VERCEL_PROJECT_PRODUCTION_URL – provided automatically by Vercel at build time
 * 3. http://localhost:3000      – local development
 */
export function getSiteUrl(): string {
  const explicit = process.env.NEXT_PUBLIC_SITE_URL;
  if (explicit) return explicit.replace(/\/+$/, "");

  const vercel = process.env.VERCEL_PROJECT_PRODUCTION_URL;
  if (vercel) return `https://${vercel.replace(/\/+$/, "")}`;

  return "http://localhost:3000";
}

export function absoluteUrl(path = "/"): string {
  return `${getSiteUrl()}${path.startsWith("/") ? path : `/${path}`}`;
}

/** True only for the real production deployment (keeps previews out of Google). */
export function isProductionDeployment(): boolean {
  if (process.env.VERCEL_ENV) return process.env.VERCEL_ENV === "production";
  return process.env.NODE_ENV === "production";
}

/* ─── Per-page metadata ──────────────────────────────────── */

type PageSeo = {
  /** Page-specific part of the title; the root template appends " | Arpit Patidar". */
  title?: string;
  description: string;
  path: `/${string}`;
};

/**
 * The card generated by app/opengraph-image.tsx. Next only attaches it to pages
 * that don't define their own `openGraph`, so every page references it explicitly.
 */
const socialImage = {
  url: "/opengraph-image",
  width: 1200,
  height: 630,
  alt: `${siteConfig.name} — ${siteConfig.jobTitle}`,
};

export function buildPageMetadata({ title, description, path }: PageSeo): Metadata {
  const socialTitle = title ? `${title} | ${siteConfig.name}` : siteConfig.title;

  return {
    ...(title ? { title } : {}),
    description,
    alternates: { canonical: path },
    openGraph: {
      title: socialTitle,
      description,
      url: path,
      type: "website",
      images: [socialImage],
    },
    twitter: {
      card: "summary_large_image",
      title: socialTitle,
      description,
      images: [socialImage],
    },
  };
}

