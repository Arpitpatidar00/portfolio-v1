/* ─── JSON-LD (schema.org) ───────────────────────────────── */

type JsonLdNode = Record<string, unknown>;

const personId = () => `${getSiteUrl()}/#person`;
const websiteId = () => `${getSiteUrl()}/#website`;

export function personJsonLd(): JsonLdNode {
  return {
    "@type": "Person",
    "@id": personId(),
    name: siteConfig.name,
    url: absoluteUrl("/"),
    image: PORTRAIT_URL,
    jobTitle: siteConfig.jobTitle,
    description: siteConfig.description,
    email: `mailto:${socialLinks.email}`,
    address: {
      "@type": "PostalAddress",
      addressCountry: "IN",
    },
    worksFor: {
      "@type": "Organization",
      name: "Metaverse Ventures Pvt. Ltd.",
    },
    alumniOf: {
      "@type": "CollegeOrUniversity",
      name: "Chameli Devi Group of Institutions",
    },
    knowsAbout: siteConfig.keywords,
    sameAs: [
      socialLinks.github,
      socialLinks.linkedin,
      socialLinks.twitter,
      socialLinks.instagram.url,
    ],
  };
}

export function websiteJsonLd(): JsonLdNode {
  return {
    "@type": "WebSite",
    "@id": websiteId(),
    url: absoluteUrl("/"),
    name: `${siteConfig.name} — Portfolio`,
    inLanguage: "en",
    author: { "@id": personId() },
    publisher: { "@id": personId() },
  };
}

export function profilePageJsonLd(path: `/${string}`, name: string): JsonLdNode {
  return {
    "@type": "ProfilePage",
    "@id": `${absoluteUrl(path)}#webpage`,
    url: absoluteUrl(path),
    name,
    isPartOf: { "@id": websiteId() },
    mainEntity: { "@id": personId() },
  };
}

export function breadcrumbJsonLd(items: { name: string; path: `/${string}` }[]): JsonLdNode {
  return {
    "@type": "BreadcrumbList",
    itemListElement: items.map((item, index) => ({
      "@type": "ListItem",
      position: index + 1,
      name: item.name,
      item: absoluteUrl(item.path),
    })),
  };
}

export function projectListJsonLd(
  projects: { title: string; category: string; year: string; link: string; image: string }[],
): JsonLdNode {
  return {
    "@type": "ItemList",
    name: `Projects by ${siteConfig.name}`,
    itemListElement: projects.map((project, index) => ({
      "@type": "ListItem",
      position: index + 1,
      item: {
        "@type": "CreativeWork",
        name: project.title,
        genre: project.category,
        dateCreated: project.year.slice(0, 4),
        creator: { "@id": personId() },
        ...(project.link ? { url: project.link } : {}),
        ...(project.image ? { image: absoluteUrl(project.image) } : {}),
      },
    })),
  };
}

/** Wraps nodes in a single @graph document. */
export function jsonLdGraph(...nodes: JsonLdNode[]): JsonLdNode {
  return { "@context": "https://schema.org", "@graph": nodes };
}
